#!/usr/bin/env python3
"""Names of the redesigned pictures in the HD pack (ui_hd), for the faithful "HD" mode that leaves them out.
Writes src/WC09Redesign.inc. Usage: gen_redesign_list.py <ui_hd folder> <out.inc>"""
import os, sys
root, out = sys.argv[1], sys.argv[2]
names = []
for r, ds, fs in os.walk(root):
    for f in fs:
        if f.endswith('.png'):
            names.append(os.path.relpath(os.path.join(r, f), root)[:-4].replace(os.sep, '/'))
names.sort()
with open(out, 'w') as o:
    o.write('// generated by wc09/tools/gen_redesign_list.py: pictures of the HD pack that are redesigns\n')
    for n in names: o.write(f'"{n}",\n')
print(len(names), 'names')
