#!/usr/bin/env python3
"""Generate WC09CardTable.h: XXH64(texel words) -> card index for the US ROM (CY8E),
plus index -> passcode. Inputs: texhash_us.tsv, cards_us.csv (made by the research tools)."""
import csv, sys
hashes, cards = sys.argv[1], sys.argv[2]
out = open(sys.argv[3], 'w')
rows = sorted(((k, int(h, 16), int(i)) for k, h, i in (l.split() for l in open(hashes))), key=lambda r: r[1])
size = {'tx128': 128, 'tx64': 64, 'tx32': 32, 'bg128': 1}  # 1 = 2D 88x128 BG tiles
pc = [0]*2934
for r in csv.DictReader(open(cards)): pc[int(r['index'])] = int(r['passcode'])
out.write('// Generated by tools/gen_cardtable.py from the user\'s own ROM (CY8E). Hashes and passcodes only.\n#pragma once\n#include "types.h"\n\nnamespace melonDS::WC09 {\n\n')
out.write('struct TexHashEntry { u64 Hash; u16 Card; u8 Size; };\n')
out.write(f'constexpr unsigned NumTexHashes = {len(rows)};\n')
out.write('constexpr TexHashEntry TexHashes[NumTexHashes] = {\n')
for k, h, i in rows: out.write(f'    {{0x{h:016x}ULL, {i}, {size[k]}}},\n')
out.write('};\n\nconstexpr unsigned NumCards = 2934;\nconstexpr u32 Passcodes[NumCards] = {\n')
for j in range(0, 2934, 8): out.write('    ' + ', '.join(str(x) for x in pc[j:j+8]) + ',\n')
out.write('};\n\n}\n')
